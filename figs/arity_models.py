#!/usr/bin/env python3
"""Which order does a growth rule require? The book's own models, counted.

Vazquez, Oliveira and Barabasi (Phys. Rev. E 71, 025103) show that the h-cycle
density of a real network is generated by the degree distribution and the
degree-dependent clustering coefficient alone,

    N_h/N = g_h sum_k P(k) ((h-1)!/2) binom(k, h-1) C(k)^(h-2),

so every cycle length follows from ONE arity-three local quantity, C(k), applied
h-2 times around the cycle. The tower of longer cycles is the product; it needs
no separate mechanism. For many real networks triangles therefore do the job.

They cannot do it for a triangle-free network. There C(k) = 0 identically and the
whole right-hand side is zero at every h >= 3 -- not an underestimate, an empty
prediction -- while the network itself is full of cycles. The book's duplication
-split rule is exactly that case, and the bubble family turns the point into a
dial, since BB(n,L) closes cycles of length L+2.

Both rules are as defined in the distance chapter:

  DS(n,q)   start from a 4-cycle. To add node i pick a random j; with probability
            q duplicate j (link i to every neighbour of j), else pick a random
            neighbour k of j and split (j,k) into (i,j) and (i,k). Duplication
            makes no triangles and splitting destroys any that might form, so
            its motif is the square.
  BB(n,L)   start from a cycle of L+2 nodes. Each step adds a chain of L new
            nodes across a randomly chosen link, closing a fresh cycle of
            length L+2. BB(n,1) is the Dorogovtsev-Mendes rule.

Exact cycle counts come from cyclecount (see cyclecount_verification.py).
Neighbour sets are iterated in sorted order throughout so the counts are
reproducible run to run.

Usage:  python3 arity_models.py
"""
import os
import random
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BINARY = os.environ.get("CYCLECOUNT", os.path.join(HERE, "cyclecount"))


def ds(n, q, seed):
    rng = random.Random(seed)
    adj = {0: {1, 3}, 1: {0, 2}, 2: {1, 3}, 3: {2, 0}}
    while len(adj) < n:
        i = len(adj)
        j = rng.choice(sorted(adj))
        if not adj[j]:
            continue
        if rng.random() < q:
            nb = sorted(adj[j])
            adj[i] = set(nb)
            for w in nb:
                adj[w].add(i)
        else:
            k = rng.choice(sorted(adj[j]))
            adj[j].discard(k)
            adj[k].discard(j)
            adj[i] = {j, k}
            adj[j].add(i)
            adj[k].add(i)
    return adj


def bb(n, L, seed):
    rng = random.Random(seed)
    m = L + 2
    adj = {v: {(v - 1) % m, (v + 1) % m} for v in range(m)}
    edges = [(v, (v + 1) % m) for v in range(m)]
    while len(adj) < n:
        u, v = edges[rng.randrange(len(edges))]
        path = [u]
        for _ in range(L):
            w = len(adj)
            adj[w] = set()
            path.append(w)
        path.append(v)
        for a, b in zip(path, path[1:]):
            adj[a].add(b)
            adj[b].add(a)
            edges.append((a, b))
    return adj


def clustering(adj):
    """Mean local clustering -- the C(k) of the generator, averaged."""
    tot, cnt = 0.0, 0
    for v, nb in adj.items():
        k = len(nb)
        if k < 2:
            continue
        nb = sorted(nb)
        links = sum(1 for a in range(k) for b in range(a + 1, k)
                    if nb[b] in adj[nb[a]])
        tot += 2 * links / (k * (k - 1))
        cnt += 1
    return tot / cnt if cnt else 0.0


def cycles(adj, lmax, budget=600):
    idx = {v: i for i, v in enumerate(sorted(adj))}
    E = sorted({(min(idx[u], idx[w]), max(idx[u], idx[w]))
                for u in adj for w in adj[u]})
    payload = f"{len(adj)} {len(E)}\n" + "\n".join(f"{a} {b}" for a, b in E) + "\n"
    out = subprocess.run([BINARY, "-l", str(lmax), "-t", str(budget)],
                         input=payload, capture_output=True, text=True)
    got = {}
    for line in out.stdout.strip().splitlines():
        a, b = line.split()
        if a != "status":
            got[int(a)] = int(b)
        elif b != "ok":
            return None
    return got


def row(label, adj, lmax):
    c = cycles(adj, lmax)
    n = len(adj)
    m = sum(len(v) for v in adj.values()) // 2
    print(f"\n{label}")
    print(f"   n={n}  m={m}  <k>={2 * m / n:.2f}  C={clustering(adj):.4f}")
    if c is None:
        print("   (cycle count exceeded its budget)")
        return
    print("   " + "  ".join(f"L{L}={c.get(L, 0)}" for L in range(3, lmax + 1)))


def main():
    print("Duplication-split: triangle-free, so the arity-three generator of")
    print("Phys. Rev. E 71, 025103 predicts zero cycles at every length.")
    for q, n in ((1 / 3, 500), (1 / 3, 2000), (2 / 5, 2000)):
        row(f"DS(n={n}, q={q:.4f})  motif = square", ds(n, q, 7), 8)

    print("\n\nThe bubble family as an arity dial: BB(n,L) closes cycles of")
    print("length L+2, and two faces sharing a link close one of length a+b-2.")
    for L in (1, 2, 3, 4):
        row(f"BB(n=4000, L={L})  motif = {L + 2}-cycle", bb(4000, L, 7), 10)


if __name__ == "__main__":
    sys.exit(main())
