#!/usr/bin/env python3
"""The cycle spectrum of the two deterministic webs against two-variable fits.

Completes pseudofractal_triples.py (triangles) and diamond_quads.py (four-cycles)
by asking the same question at every cycle length at once.

The point is structural rather than numerical. For a model with independent links
and expected adjacency P, the expected number of L-cycles on distinct vertices is
tr(P^L)/(2L) to leading order, and for a K-block fit P collapses to a K x K
transfer matrix

    T_rs = omega_rs * sqrt(Q_r Q_s)     (degree-corrected, Q_r = sum of k^2 in r)
    T_rs = p_rs * sqrt(n_r n_s)         (plain)

so the entire spectrum is generated by a K x K matrix and is a smooth geometric
profile in L, asymptotically lambda^L/(2L) for the leading eigenvalue lambda. A
two-variable model has no freedom to put a feature at one particular length.

The lattices do exactly that. The diamond's cycles live only at L = 4, 8, 16, ...
and are exactly zero elsewhere; the pseudofractal carries an excess at L = 3.

Usage:  python3 motif_spectrum.py
"""
import numpy as np

LMAX = 8


def pseudofractal(t):
    edges = [(0, 1), (0, 2), (1, 2)]
    n, eb, br = 3, [0, 1, 2], {0: -1, 1: -1, 2: -1}
    for _ in range(t):
        ne, nb = [], []
        for (u, v), b in zip(edges, eb):
            w = n; n += 1; br[w] = b
            ne += [(u, v), (u, w), (v, w)]; nb += [b, b, b]
        edges, eb = ne, nb
    E = set(tuple(sorted(e)) for e in edges)
    return n, E, np.array([br[i] for i in range(n)])


def diamond(t):
    edges, eb, n, br = [(0, 1)], [-1], 2, {0: -1, 1: -1}
    for gen in range(t):
        ne, nb = [], []
        for (u, v), b in zip(edges, eb):
            for path in range(2):
                w = n; n += 1
                lab = path if gen == 0 else b
                br[w] = lab
                ne += [(u, w), (w, v)]; nb += [lab, lab]
        edges, eb = ne, nb
    E = set(tuple(sorted(e)) for e in edges)
    return n, E, np.array([br[i] for i in range(n)])


def true_cycles(n, E, Lmax):
    """Exact simple-cycle counts. Each cycle is enumerated from its smallest
    vertex in both directions, so the tallies are halved."""
    adj = [[] for _ in range(n)]
    for u, v in E:
        adj[u].append(v); adj[v].append(u)
    counts = [0] * (Lmax + 1)
    for s in range(n):
        stack = [(s, 1, {s})]
        while stack:
            v, ln, seen = stack.pop()
            for w in adj[v]:
                if w == s and ln >= 3:
                    counts[ln] += 1
                elif w > s and w not in seen and ln < Lmax:
                    stack.append((w, ln + 1, seen | {w}))
    return [c // 2 for c in counts]


def transfer(n, E, br, degree_corrected):
    """K x K transfer matrix of the fitted two-block model."""
    A = np.zeros((n, n))
    for u, v in E:
        A[u, v] = A[v, u] = 1.0
    k = A.sum(1)
    g = np.where(br == 1, 1, 0)
    N = [int((g == r).sum()) for r in (0, 1)]
    Q = [float((k[g == r] ** 2).sum()) for r in (0, 1)]
    S = [float(k[g == r].sum()) for r in (0, 1)]
    T = np.zeros((2, 2))
    for r in (0, 1):
        for s in (0, 1):
            e = A[np.ix_(g == r, g == s)].sum()
            if degree_corrected:
                T[r, s] = e / (S[r] * S[s]) * np.sqrt(Q[r] * Q[s])
            else:
                pairs = N[r] * N[s] if r != s else N[r] * (N[r] - 1)
                T[r, s] = e / pairs * np.sqrt(N[r] * N[s])
    return T


def spectrum(T, Lmax):
    return [np.trace(np.linalg.matrix_power(T, L)) / (2 * L) if L else 0.0
            for L in range(Lmax + 1)]


if __name__ == "__main__":
    for label, build, t in [("pseudofractal web (rule closes triangles)", pseudofractal, 5),
                            ("diamond lattice (rule doubles a link)", diamond, 5)]:
        n, E, br = build(t)
        true = true_cycles(n, E, LMAX)
        Tp, Td = transfer(n, E, br, False), transfer(n, E, br, True)
        sp, sd = spectrum(Tp, LMAX), spectrum(Td, LMAX)
        lp = max(abs(np.linalg.eigvals(Tp)))
        ld = max(abs(np.linalg.eigvals(Td)))
        print(f"\n{label}:  t={t}, n={n}, m={len(E)}, <k>={2*len(E)/n:.2f}")
        print(f"  leading eigenvalue  plain {lp:.3f}   degree-corrected {ld:.3f}")
        print(f"  {'L':>3} {'true':>10} {'plain':>10} {'degree-corr':>12}")
        for L in range(3, LMAX + 1):
            print(f"  {L:>3} {true[L]:>10} {sp[L]:>10.2f} {sd[L]:>12.2f}")

    print("\n  The diamond is exactly zero at L = 3, 5, 6, 7 and nonzero at 4 and 8;")
    print("  both fitted models put positive mass at every length.")
